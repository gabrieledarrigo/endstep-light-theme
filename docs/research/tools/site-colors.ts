import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import postcss, { type AtRule, type Container, type Rule } from "postcss";
import {
  DARK_TOKENS,
  EXACT,
  EXCLUDED_TOKENS,
  KEEP,
  LIGHT_CSS,
  LIGHT_SELECTOR,
  NEAR,
  SITE,
  TEXT_TOKENS,
  candidateTokens,
  fetchText,
  isBlackOrWhite,
  nearestToken,
  parseColour,
  readTokens,
  sameRgb,
  type Rgba,
} from "./colours.ts";

type Declaration = {
  name: string;
  value: string;
  important: boolean;
};

type Override = {
  atRules: string[];
  selector: string;
  declarations: Declaration[];
};

type Report = {
  counts: Record<string, number>;
  review: Record<string, string[]>;
  keyframes: string[];
  url: string[];
  nested: string[];
};

const BLOCK_START =
  "/* Generated by docs/research/tools/site-colors.ts. Do not edit by hand. */";
const BLOCK_END = "/* End of the generated block. */";
const TEXT_PROPERTIES = new Set([
  "color",
  "-webkit-text-fill-color",
  "caret-color",
  "text-decoration-color",
]);
const TAILWIND_PALETTE =
  /^--color-(black|white|(red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose|slate|gray|zinc|neutral|stone|taupe|mauve|mist|olive)-\d+)$/;
const COLOUR = /#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|oklch|oklab)\([^()]*\)/g;

/**
 * Rules whose colours all stay as they are, grouped by the reason.
 */
const KEPT_SELECTORS: Readonly<Record<string, RegExp>> = {
  "mana symbols (Mana font and mana coins)":
    /(^|[\s,>+~])\.(ms|wr-mana-coin)(?![\w])|\.ms-[\w-]+/,
  "medal art": /\.es-medal/,
  "deck sheet, already a light parchment on the site": /\.wr-ds-active/,
};

/**
 * Downloads the stylesheets linked by the home page and every CSS chunk named in the main bundle, sorted by name.
 */
async function downloadStylesheets(
  outDir: string,
): Promise<Map<string, string>> {
  const home = await fetchText(`${SITE}/`);
  const mainName = home.match(/src="\/assets\/(main-[\w-]+\.js)"/)?.[1];
  if (!mainName) {
    throw new Error("The site changed: the main bundle is missing.");
  }
  const main = await fetchText(`${SITE}/assets/${mainName}`);
  const names = new Set([
    ...[...home.matchAll(/\/assets\/([\w.-]+\.css)/g)].map((m) => m[1]),
    ...[...main.matchAll(/([\w.-]+-[\w-]{8}\.css)/g)].map((m) => m[1]),
  ]);

  const cssDir = path.join(outDir, "css");
  await mkdir(cssDir, { recursive: true });
  const sheets = new Map<string, string>();
  for (const name of [...names].filter(isString).sort()) {
    const sheet = await fetchText(`${SITE}/assets/${name}`);
    sheets.set(name, sheet);
    await writeFile(path.join(cssDir, name), sheet);
  }
  return sheets;
}

function isString(value: string | undefined): value is string {
  return value !== undefined;
}

/**
 * The at-rules around a rule, from the outermost to the innermost, such as `@media (hover:hover)`.
 */
function atRulesOf(rule: Rule): string[] {
  const preludes: string[] = [];
  let parent: Container | undefined = rule.parent;
  while (parent && parent.type === "atrule") {
    const atRule = parent as AtRule;
    preludes.unshift(`@${atRule.name} ${atRule.params}`.trim());
    parent = atRule.parent;
  }
  return preludes;
}

function isLayer(prelude: string): boolean {
  return prelude.startsWith("@layer");
}

function isColourMixSupport(prelude: string): boolean {
  return prelude.startsWith("@supports") && prelude.includes("color-mix");
}

function isKeyframes(prelude: string): boolean {
  return (
    prelude.startsWith("@keyframes") || prelude.startsWith("@-webkit-keyframes")
  );
}

/**
 * Identifies a declaration across the Tailwind fallback and its @supports version.
 */
function ruleKey(atRules: string[], selector: string, name: string): string {
  const kept = atRules.filter(
    (prelude) => !isLayer(prelude) && !isColourMixSupport(prelude),
  );
  return [...kept, selector, name].join("\u0000");
}

function declarationsOf(rule: Rule): Declaration[] {
  const declarations: Declaration[] = [];
  rule.each((node) => {
    if (node.type === "decl") {
      declarations.push({
        name: node.prop,
        value: node.value,
        important: node.important,
      });
    }
  });
  return declarations;
}

/**
 * Finds every colour in a value that is not inside var() or url().
 */
function colourSpans(
  value: string,
): { start: number; end: number; literal: string }[] {
  return [...value.matchAll(COLOUR)]
    .filter((match) => !insideFunction(value, match.index, ["var", "url"]))
    .map((match) => ({
      start: match.index,
      end: match.index + match[0].length,
      literal: match[0],
    }));
}

function insideFunction(
  text: string,
  position: number,
  names: readonly string[],
): boolean {
  const stack: string[] = [];
  for (const match of text.slice(0, position).matchAll(/([\w-]*)\(|\)/g)) {
    if (match[0] === ")") {
      stack.pop();
    } else {
      stack.push(match[1] ?? "");
    }
  }
  return stack.some((name) => names.includes(name));
}

/**
 * Scopes a selector list to the light theme. Returns undefined when nothing is left to scope.
 */
function scoped(selector: string): string | undefined {
  const parts = postcss.list
    .comma(selector)
    .map((part) => part.trim())
    .filter((part) => !part.startsWith(":host"))
    .map((part) => {
      if (part.startsWith(":root")) {
        return LIGHT_SELECTOR + part.slice(":root".length);
      }
      if (/^html(?![\w-])/.test(part)) {
        return LIGHT_SELECTOR + part.slice("html".length);
      }
      return `${LIGHT_SELECTOR} ${part}`;
    });
  return parts.length > 0 ? parts.join(", ") : undefined;
}

/**
 * The site selectors that light.css overrides by hand, above the generated block.
 */
function manualSelectors(lightCss: string): Set<string> {
  const manual = lightCss.split(BLOCK_START)[0] ?? "";
  const selectors = new Set<string>();
  postcss.parse(manual).walkRules((rule) => {
    for (const part of rule.selectors) {
      if (part.startsWith(`${LIGHT_SELECTOR} `)) {
        selectors.add(part.slice(LIGHT_SELECTOR.length + 1));
      }
    }
  });
  return selectors;
}

class Mapper {
  private readonly dark: Map<string, Rgba>;
  private readonly light: Map<string, Rgba>;
  private readonly opaque: string[];
  private readonly textCandidates: string[];
  private readonly otherCandidates: string[];
  private readonly kept: Rgba[];

  constructor(dark: Map<string, Rgba>, light: Map<string, Rgba>) {
    const candidates = candidateTokens(dark, light);
    this.dark = dark;
    this.light = light;
    this.opaque = [...dark].flatMap(([name, colour]) =>
      colour[3] >= 1 ? [name] : [],
    );
    this.textCandidates = candidates.filter(
      (name) => TEXT_TOKENS.test(name) || name === "--color-accent-chrome",
    );
    this.otherCandidates = candidates.filter((name) => !TEXT_TOKENS.test(name));
    this.kept = Object.values(KEEP)
      .flat()
      .map(parseColour)
      .filter((colour): colour is Rgba => colour !== undefined);
  }

  hasLightToken(name: string): boolean {
    return this.light.has(name);
  }

  /**
   * Returns the light replacement of a colour, or undefined with the reason to keep it.
   */
  map(colour: Rgba, isText: boolean): { replacement?: string; reason: string } {
    if (
      this.kept.some((kept) => sameRgb(kept, colour)) ||
      isBlackOrWhite(colour)
    ) {
      return { reason: "kept" };
    }
    if (colour[3] === 0) {
      return { reason: "transparent" };
    }
    const closest = nearestToken(colour, this.opaque, this.dark);
    if (EXCLUDED_TOKENS.test(closest.token) && closest.distance < EXACT) {
      return { reason: "meaning" };
    }
    const { token, distance } = nearestToken(
      colour,
      isText ? this.textCandidates : this.otherCandidates,
      this.dark,
    );
    if (distance >= NEAR) {
      return { reason: "review" };
    }
    if (colour[3] >= 1) {
      return { replacement: `var(${token})`, reason: "mapped" };
    }
    const percent = (colour[3] * 100).toFixed(1).replace(/\.0$/, "");
    return {
      replacement: `color-mix(in srgb, var(${token}) ${percent}%, transparent)`,
      reason: "mapped",
    };
  }
}

/**
 * Collects the declarations that a later `@supports (color: color-mix(...))` rule replaces with a variable.
 */
function replacedByVariable(sheets: Map<string, string>): Set<string> {
  const keys = new Set<string>();
  for (const sheet of sheets.values()) {
    postcss.parse(sheet).walkRules((rule) => {
      const atRules = atRulesOf(rule);
      if (!atRules.some(isColourMixSupport)) {
        return;
      }
      for (const { name, value } of declarationsOf(rule)) {
        if (value.includes("var(")) {
          keys.add(ruleKey(atRules, rule.selector, name));
        }
      }
    });
  }
  return keys;
}

function analyse(
  sheets: Map<string, string>,
  mapper: Mapper,
  manual: Set<string>,
): { overrides: Override[]; report: Report } {
  const fallbacks = replacedByVariable(sheets);
  const overrides: Override[] = [];
  const report: Report = {
    counts: {},
    review: {},
    keyframes: [],
    url: [],
    nested: [],
  };
  const count = (reason: string, amount = 1) => {
    report.counts[reason] = (report.counts[reason] ?? 0) + amount;
  };

  for (const [sheetName, sheet] of sheets) {
    postcss.parse(sheet).walkRules((rule) => {
      const selector = rule.selector;
      if (rule.parent?.type === "rule") {
        report.nested.push(`${sheetName}: ${selector}`);
        return;
      }
      const atRules = atRulesOf(rule);
      const inKeyframes = atRules.some(isKeyframes);
      const inColourMixSupport = atRules.some(isColourMixSupport);
      const keptGroup = Object.entries(KEPT_SELECTORS).find(([, pattern]) =>
        pattern.test(selector),
      )?.[0];
      const changed: Declaration[] = [];

      for (const { name, value, important } of declarationsOf(rule)) {
        if (value.includes("url(") && /%23[0-9a-fA-F]{3,8}/.test(value)) {
          report.url.push(`${sheetName}: ${selector} { ${name} }`);
        }
        const spans = colourSpans(value);
        if (spans.length === 0) {
          continue;
        }
        if (inKeyframes) {
          report.keyframes.push(
            `${sheetName}: ${atRules.join(" ")} ${selector} { ${name}: ${value} }`,
          );
          count("keyframes", spans.length);
          continue;
        }
        if (
          !inColourMixSupport &&
          fallbacks.has(ruleKey(atRules, selector, name))
        ) {
          count("tailwind fallback", spans.length);
          continue;
        }
        if (
          postcss.list.comma(selector).every((part) => manual.has(part.trim()))
        ) {
          count("manual rule in light.css", spans.length);
          continue;
        }
        if (keptGroup) {
          count(`kept: ${keptGroup}`, spans.length);
          continue;
        }
        if (
          name.startsWith("--") &&
          (mapper.hasLightToken(name) || TAILWIND_PALETTE.test(name))
        ) {
          count(
            mapper.hasLightToken(name)
              ? "token already in light.css"
              : "tailwind palette",
            spans.length,
          );
          continue;
        }

        let newValue = value;
        let offset = 0;
        for (const { start, end, literal } of spans) {
          const colour = parseColour(literal);
          if (!colour) {
            count("unparsed");
            continue;
          }
          const { replacement, reason } = mapper.map(
            colour,
            TEXT_PROPERTIES.has(name),
          );
          count(reason);
          if (reason === "review") {
            (report.review[literal] ??= []).push(`${selector} { ${name} }`);
          }
          if (replacement) {
            newValue =
              newValue.slice(0, start + offset) +
              replacement +
              newValue.slice(end + offset);
            offset += replacement.length - (end - start);
          }
        }
        if (newValue !== value) {
          changed.push({ name, value: newValue, important });
        }
      }

      const scopedSelector = scoped(selector);
      if (changed.length > 0 && scopedSelector) {
        overrides.push({
          atRules: atRules.filter((prelude) => !isLayer(prelude)),
          selector: scopedSelector,
          declarations: changed,
        });
      }
    });
  }
  return { overrides, report };
}

function render(overrides: Override[]): string {
  const lines = [BLOCK_START, ""];
  for (const { atRules, selector, declarations } of overrides) {
    let indent = "";
    for (const prelude of atRules) {
      lines.push(`${indent}${prelude} {`);
      indent += "  ";
    }
    lines.push(`${indent}${selector} {`);
    for (const { name, value, important } of declarations) {
      lines.push(
        `${indent}  ${name}: ${value}${important ? " !important" : ""};`,
      );
    }
    lines.push(`${indent}}`);
    for (let level = atRules.length; level > 0; level -= 1) {
      indent = indent.slice(2);
      lines.push(`${indent}}`);
    }
    lines.push("");
  }
  lines.push(BLOCK_END);
  return `${lines.join("\n")}\n`;
}

/**
 * Finds the fixed dark colours in the endstep.cc stylesheets, and writes the light overrides into src/theme/light.css.
 *
 * Usage: `node docs/research/tools/site-colors.ts OUT_DIR [--write]`
 *
 * It downloads every stylesheet of the site into OUT_DIR/css, and writes the full report to OUT_DIR/site-colors.json.
 * With --write, it replaces the generated block at the end of src/theme/light.css. Without it, it prints the block.
 * After --write, run `npx prettier --write src/theme/light.css`.
 *
 * The tokens in light.css change every site rule that reads a variable.
 * This script handles the rules that write a colour directly, such as a Tailwind arbitrary class.
 *
 * Every colour maps to the opaque dark token that is nearest in OKLab, never a mana or chart series token.
 * A text colour only maps to a text token (or the accent used as text), any other property never maps to a text token.
 * Several tokens share a dark value (--color-void and --color-text-inverse are both #0a0806), so the property decides the role.
 * The override reads the light token with var(), so it follows the theme. An alpha below 1 becomes a color-mix().
 *
 * These colours stay as they are:
 * - every colour in the rules that KEPT_SELECTORS lists: mana symbols, medal art, and the deck sheet
 * - black and white (shadows and highlights), and the colours in KEEP
 * - colours that are copies of a mana or chart series token, so they keep their meaning
 * - colours far from every dark token (distance from NEAR up). The report lists them under "review".
 *
 * These declarations are skipped:
 * - Tailwind fallbacks that a later @supports rule replaces with a variable
 * - colours inside var() fallbacks and url() data
 * - rules that light.css already overrides by hand, above the generated block
 * - token definitions that light.css already overrides, and the Tailwind default palette
 * - @keyframes, which a selector cannot scope. The report lists them.
 *
 * To handle a colour under "review", write a rule by hand in light.css, above the generated block.
 * The script then skips that selector.
 */
async function main(): Promise<void> {
  const [outDir, flag] = process.argv.slice(2);
  if (!outDir) {
    throw new Error(
      "Usage: node docs/research/tools/site-colors.ts OUT_DIR [--write]",
    );
  }
  await mkdir(outDir, { recursive: true });
  const sheets = await downloadStylesheets(outDir);
  const lightCss = await readFile(LIGHT_CSS, "utf8");
  const dark = readTokens(await readFile(DARK_TOKENS, "utf8"), ":root");
  const light = readTokens(lightCss, LIGHT_SELECTOR);
  const mapper = new Mapper(dark, light);
  const { overrides, report } = analyse(
    sheets,
    mapper,
    manualSelectors(lightCss),
  );

  await writeFile(
    path.join(outDir, "site-colors.json"),
    JSON.stringify(
      {
        ...report,
        stylesheets: [...sheets.keys()],
        "override rules": overrides.length,
      },
      null,
      1,
    ),
  );
  console.error(
    `stylesheets: ${sheets.size} | override rules: ${overrides.length}`,
  );
  console.error(`colours by outcome: ${JSON.stringify(report.counts)}`);
  console.error(
    `colours to review: ${Object.keys(report.review).length} | keyframes: ${report.keyframes.length} ` +
      `| url data with colours: ${report.url.length} | nested rules: ${report.nested.length}`,
  );

  const block = render(overrides);
  if (flag === "--write") {
    const manual = (lightCss.split(BLOCK_START)[0] ?? "").trimEnd();
    await writeFile(LIGHT_CSS, `${manual}\n\n${block}`);
  } else {
    console.log(block);
  }
}

await main();
