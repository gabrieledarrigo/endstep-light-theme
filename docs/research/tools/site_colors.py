"""Find the fixed dark colours in the endstep.cc stylesheets, and write the light overrides into src/theme/light.css.

Usage: python3 docs/research/tools/site_colors.py OUT_DIR [--write]

Downloads every stylesheet of the site into OUT_DIR/css and writes the full report to OUT_DIR/site-colors.json.
With --write, it replaces the generated block at the end of src/theme/light.css. Without it, it prints the block.
After --write, run `npx prettier --write src/theme/light.css`.

A colour that the script cannot map ends in the report under "review".
To handle it, write a rule by hand in light.css, above the generated block: the script then skips that selector.

The tokens in light.css change every site rule that reads a variable.
This script handles the rules that write a colour directly, such as `.wr-zone-panel { background: #0a0806d6 }`.

Every colour in a declaration is mapped like in inline_colors.py:
to the opaque dark token that is nearest in OKLab, never a mana or chart series token,
A text colour only maps to a text token (or the accent used as text), any other property never maps to a text token.
Several tokens share a dark value (--color-void and --color-text-inverse are both #0a0806), so the property decides the role.
The override reads the light token with var(), so it follows the theme. An alpha below 1 becomes a color-mix().

These colours are kept as they are:
  - every colour in the rules that KEPT_SELECTORS lists: mana symbols, medal art, and the deck sheet
  - black and white (shadows and highlights), and the colours in KEEP of inline_colors.py
  - colours that are copies of a mana or chart series token, so they keep their meaning
  - colours that are far from every dark token (distance from NEAR up): they are illustrations or already light,
    and the report lists them for a manual check

These declarations are skipped:
  - Tailwind fallbacks that a later @supports rule replaces with a variable
  - colours inside var() fallbacks and url() data
  - rules that light.css already overrides by hand, outside the generated block
  - token definitions that light.css already overrides, and the Tailwind default palette
  - @keyframes, which a selector cannot scope; the report lists them
"""
import json
import math
import re
import sys
import urllib.request
from pathlib import Path

from inline_colors import (
    DARK_TOKENS,
    EXCLUDED_TOKENS,
    KEEP,
    LIGHT_TOKENS,
    NEAR,
    EXACT,
    SITE,
    TEXT_TOKENS,
    candidate_tokens,
    oklch_to_rgb,
    parse_colour,
    read_tokens,
    rgb_to_oklab,
)

PREFIX = 'html[data-elt-theme="light"]'
BLOCK_START = "/* Generated by docs/research/tools/site_colors.py. Do not edit by hand. */"
BLOCK_END = "/* End of the generated block. */"
TEXT_PROPERTIES = {"color", "-webkit-text-fill-color", "caret-color", "text-decoration-color"}
TAILWIND_PALETTE = re.compile(
    r"^--color-(black|white|(red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple"
    r"|fuchsia|pink|rose|slate|gray|zinc|neutral|stone|taupe|mauve|mist|olive)-\d+)$"
)
COLOUR = re.compile(r"#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?|oklch|oklab)\([^()]*\)")
KEPT_SELECTORS = {
    "mana symbols (Mana font and mana coins)": re.compile(r"(^|[\s,>+~])\.(ms|wr-mana-coin)(?![\w])|\.ms-[\w-]+"),
    "medal art": re.compile(r"\.es-medal"),
    "deck sheet, already a light parchment on the site": re.compile(r"\.wr-ds-active"),
}


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(request) as response:
        return response.read().decode("utf-8")


def download_stylesheets(out_dir):
    """Download the stylesheets linked by the home page and every CSS chunk named in the main bundle."""
    home = fetch(SITE + "/")
    main_name = re.search(r'src="/assets/(main-[\w-]+\.js)"', home).group(1)
    main = fetch(f"{SITE}/assets/{main_name}")
    names = set(re.findall(r'/assets/([\w.-]+\.css)', home))
    names |= set(re.findall(r'([\w.-]+-[\w-]{8}\.css)', main))
    css_dir = out_dir / "css"
    css_dir.mkdir(parents=True, exist_ok=True)
    sheets = {}
    for name in sorted(names):
        sheets[name] = fetch(f"{SITE}/assets/{name}")
        (css_dir / name).write_text(sheets[name])
    return sheets


def parse_any_colour(text):
    """Like parse_colour, plus the CSS Color 4 forms that minified stylesheets use."""
    colour = parse_colour(text)
    if colour:
        return colour
    match = re.fullmatch(r"(rgba?|oklch|oklab)\(\s*([^()]*)\)", text.strip())
    if not match:
        return None
    function, arguments = match.groups()
    channels, _, alpha_text = arguments.partition("/")
    parts = channels.replace(",", " ").split()
    if len(parts) == 4 and not alpha_text:
        parts, alpha_text = parts[:3], parts[3]
    if len(parts) != 3:
        return None
    alpha = number(alpha_text) if alpha_text.strip() else 1.0
    if alpha is None:
        return None
    if function.startswith("rgb"):
        values = [number(part, 255) for part in parts]
        if None in values:
            return None
        return (*(round(v) for v in values), alpha)
    lightness, a, b = number(parts[0], 1), number(parts[1]), number(parts[2])
    if None in (lightness, a, b):
        return None
    if function == "oklab":
        chroma, hue = math.hypot(a, b), math.degrees(math.atan2(b, a))
    else:
        chroma, hue = a, b
    return (*oklch_to_rgb(lightness, chroma, hue), alpha)


def number(text, percent_scale=1.0):
    text = text.strip()
    try:
        if text.endswith("%"):
            return float(text[:-1]) / 100 * percent_scale
        return float(text)
    except ValueError:
        return None


def split_top_level(text, separator):
    """Split on a separator that is not inside parentheses, brackets or quotes."""
    parts, depth, quote, start = [], 0, None, 0
    for index, char in enumerate(text):
        if quote:
            if char == quote and text[index - 1] != "\\":
                quote = None
        elif char in "\"'":
            quote = char
        elif char in "([":
            depth += 1
        elif char in ")]":
            depth -= 1
        elif char == separator and depth == 0:
            parts.append(text[start:index])
            start = index + 1
    parts.append(text[start:])
    return parts


def parse_rules(css):
    """Return (at-rule preludes, selector, body) for every style rule. Rules with nested rules are returned with body None."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    rules, stack, start, index, quote = [], [], 0, 0, None
    while index < len(css):
        char = css[index]
        if quote:
            if char == quote and css[index - 1] != "\\":
                quote = None
        elif char in "\"'":
            quote = char
        elif char == "{":
            prelude = css[start:index].strip()
            if prelude.startswith("@"):
                stack.append(prelude)
                start = index + 1
            else:
                end = matching_brace(css, index)
                body = css[index + 1:end]
                rules.append((tuple(stack), prelude, None if "{" in body else body))
                index = end
                start = end + 1
        elif char == "}":
            if stack:
                stack.pop()
            start = index + 1
        elif char == ";":
            start = index + 1
        index += 1
    return rules


def matching_brace(css, opening):
    depth, quote = 0, None
    for index in range(opening, len(css)):
        char = css[index]
        if quote:
            if char == quote and css[index - 1] != "\\":
                quote = None
        elif char in "\"'":
            quote = char
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return index
    return len(css)


def declarations(body):
    result = []
    for part in split_top_level(body, ";"):
        name, colon, value = part.partition(":")
        if not colon:
            continue
        value = value.strip()
        important = value.endswith("!important")
        if important:
            value = value[: -len("!important")].strip()
        result.append((name.strip(), value, important))
    return result


def colour_spans(value):
    """Return the (start, end, text) of every colour that is not inside var() or url()."""
    spans = []
    for match in COLOUR.finditer(value):
        if not inside_function(value, match.start(), ("var", "url")):
            spans.append((match.start(), match.end(), match.group(0)))
    return spans


def inside_function(text, position, names):
    stack = []
    for match in re.finditer(r"([\w-]*)\(|\)", text[:position]):
        if match.group(0) == ")":
            if stack:
                stack.pop()
        else:
            stack.append(match.group(1))
    return any(name in names for name in stack)


def is_layer(prelude):
    return prelude.startswith("@layer")


def is_colour_mix_support(prelude):
    return prelude.startswith("@supports") and "color-mix" in prelude


def rule_key(at_rules, selector, name):
    kept = tuple(p for p in at_rules if not is_layer(p) and not is_colour_mix_support(p))
    return kept, selector, name


def prefixed(selector):
    """Scope a selector list to the light theme. Returns None when nothing is left to scope."""
    parts = []
    for part in split_top_level(selector, ","):
        part = part.strip()
        if part.startswith(":host"):
            continue
        if part.startswith(":root"):
            parts.append(PREFIX + part[len(":root"):])
        elif re.match(r"html(?![\w-])", part):
            parts.append(PREFIX + part[len("html"):])
        else:
            parts.append(f"{PREFIX} {part}")
    return ", ".join(parts) if parts else None


def manual_selectors(light_css):
    """Selectors that light.css overrides by hand, outside the generated block."""
    manual = light_css.split(BLOCK_START)[0]
    selectors = set()
    for _, selector, _ in parse_rules(manual):
        for part in split_top_level(selector, ","):
            part = part.strip()
            if part.startswith(PREFIX + " "):
                selectors.add(part[len(PREFIX) + 1:])
    return selectors


class Mapper:
    def __init__(self, dark, light):
        self.dark = dark
        self.light = light
        self.candidates = candidate_tokens(dark, light)
        self.text_candidates = [
            name for name in self.candidates if TEXT_TOKENS.match(name) or name == "--color-accent-chrome"
        ]
        self.other_candidates = [name for name in self.candidates if not TEXT_TOKENS.match(name)]
        self.opaque = [name for name in dark if dark[name][3] >= 1]
        self.kept = {parse_colour(c)[:3] for colours in KEEP.values() for c in colours}

    def nearest(self, colour, names):
        target = rgb_to_oklab(*colour[:3])
        best = min(names, key=lambda name: math.dist(target, rgb_to_oklab(*self.dark[name][:3])))
        return best, math.dist(target, rgb_to_oklab(*self.dark[best][:3]))

    def map(self, colour, is_text):
        """Return (replacement or None, reason)."""
        if colour[:3] in self.kept or colour[:3] in ((0, 0, 0), (255, 255, 255)):
            return None, "kept"
        if colour[3] == 0:
            return None, "transparent"
        closest, distance = self.nearest(colour, self.opaque)
        if EXCLUDED_TOKENS.match(closest) and distance < EXACT:
            return None, "meaning"
        token, distance = self.nearest(colour, self.text_candidates if is_text else self.other_candidates)
        if distance >= NEAR:
            return None, "review"
        if colour[3] >= 1:
            return f"var({token})", "mapped"
        percent = f"{colour[3] * 100:.1f}".rstrip("0").rstrip(".")
        return f"color-mix(in srgb, var({token}) {percent}%, transparent)", "mapped"


def analyse(sheets, mapper, manual):
    replaced_by_variable = set()
    for sheet in sheets.values():
        for at_rules, selector, body in parse_rules(sheet):
            if body is None or not any(is_colour_mix_support(p) for p in at_rules):
                continue
            for name, value, _ in declarations(body):
                if "var(" in value:
                    replaced_by_variable.add(rule_key(at_rules, selector, name))

    overrides, report = [], {"counts": {}, "review": {}, "keyframes": [], "url": [], "nested": []}

    def count(reason, amount=1):
        report["counts"][reason] = report["counts"].get(reason, 0) + amount

    for sheet_name, sheet in sheets.items():
        for at_rules, selector, body in parse_rules(sheet):
            if body is None:
                report["nested"].append(f"{sheet_name}: {selector}")
                continue
            in_keyframes = any(p.startswith(("@keyframes", "@-webkit-keyframes")) for p in at_rules)
            kept_group = next((group for group, pattern in KEPT_SELECTORS.items() if pattern.search(selector)), None)
            changed = []
            for name, value, important in declarations(body):
                if "url(" in value and re.search(r"%23[0-9a-fA-F]{3,8}", value):
                    report["url"].append(f"{sheet_name}: {selector} {{ {name} }}")
                spans = colour_spans(value)
                if not spans:
                    continue
                if in_keyframes:
                    report["keyframes"].append(f"{sheet_name}: {' '.join(at_rules)} {selector} {{ {name}: {value} }}")
                    count("keyframes", len(spans))
                    continue
                if not any(is_colour_mix_support(p) for p in at_rules) and rule_key(at_rules, selector, name) in replaced_by_variable:
                    count("tailwind fallback", len(spans))
                    continue
                if selector in manual:
                    count("manual rule in light.css", len(spans))
                    continue
                if kept_group:
                    count(f"kept: {kept_group}", len(spans))
                    continue
                if name.startswith("--") and (name in mapper.light or TAILWIND_PALETTE.match(name)):
                    count("token already in light.css" if name in mapper.light else "tailwind palette", len(spans))
                    continue
                new_value, offset, any_change = value, 0, False
                for start, end, literal in spans:
                    colour = parse_any_colour(literal)
                    if not colour:
                        count("unparsed")
                        continue
                    replacement, reason = mapper.map(colour, name in TEXT_PROPERTIES)
                    count(reason)
                    if reason == "review":
                        report["review"].setdefault(literal, []).append(f"{selector} {{ {name} }}")
                    if replacement:
                        new_value = new_value[: start + offset] + replacement + new_value[end + offset:]
                        offset += len(replacement) - (end - start)
                        any_change = True
                if any_change:
                    changed.append((name, new_value, important))
            scoped = prefixed(selector)
            if changed and scoped:
                outer = tuple(p for p in at_rules if not is_layer(p))
                overrides.append((outer, scoped, changed))
    return overrides, report


def render(overrides):
    lines = [BLOCK_START, ""]
    for at_rules, selector, changed in overrides:
        indent = ""
        for prelude in at_rules:
            lines.append(f"{indent}{prelude} {{")
            indent += "  "
        lines.append(f"{indent}{selector} {{")
        for name, value, important in changed:
            lines.append(f"{indent}  {name}: {value}{' !important' if important else ''};")
        lines.append(f"{indent}}}")
        for _ in at_rules:
            indent = indent[:-2]
            lines.append(f"{indent}}}")
        lines.append("")
    lines.append(BLOCK_END)
    return "\n".join(lines) + "\n"


def write_block(light_css, block):
    manual = light_css.split(BLOCK_START)[0].rstrip() + "\n\n"
    return manual + block


def main():
    out_dir = Path(sys.argv[1])
    write = "--write" in sys.argv[2:]
    sheets = download_stylesheets(out_dir)
    light_css = LIGHT_TOKENS.read_text()
    mapper = Mapper(read_tokens(DARK_TOKENS, root_blocks_only=True), read_tokens(LIGHT_TOKENS, root_blocks_only=False))
    overrides, report = analyse(sheets, mapper, manual_selectors(light_css))
    report["stylesheets"] = sorted(sheets)
    report["override rules"] = len(overrides)
    (out_dir / "site-colors.json").write_text(json.dumps(report, indent=1))

    print(f"stylesheets: {len(sheets)} | override rules: {len(overrides)}", file=sys.stderr)
    print(f"colours by outcome: {json.dumps(report['counts'])}", file=sys.stderr)
    print(f"colours to review: {len(report['review'])} | keyframes: {len(report['keyframes'])} "
          f"| url data with colours: {len(report['url'])} | nested rules: {len(report['nested'])}", file=sys.stderr)

    block = render(overrides)
    if write:
        LIGHT_TOKENS.write_text(write_block(light_css, block))
    else:
        print(block)


if __name__ == "__main__":
    main()
